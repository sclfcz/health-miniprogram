// 云函数入口函数
exports.main = async (event, context) => {
  try {
    const results = []
    
    for (const item of knowledgeData) {
      try {
        // 检查是否已存在
        const existResult = await db.collection('medical_knowledge')
          .doc(item._id)
          .get()
          .catch(() => null)
        
        if (existResult && existResult.data) {
          // 更新已存在的数据
          await db.collection('medical_knowledge')
            .doc(item._id)
            .update({
              data: {
                title: item.title,
                tag: item.tag,
                summary: item.summary,
                content: item.content,
                cover_url: item.cover_url
              }
            })
          results.push({
            _id: item._id,
            action: 'updated'
          })
        } else {
          // 插入新数据
          await db.collection('medical_knowledge')
            .add({
              data: item
            })
          results.push({
            _id: item._id,
            action: 'inserted'
          })
        }
      } catch (err) {
        results.push({
          _id: item._id,
          action: 'failed',
          error: err.message
        })
      }
    }
    
    return {
      success: true,
      message: '健康知识库数据初始化完成',
      total: knowledgeData.length,
      results: results
    }
  } catch (err) {
    return {
      success: false,
      error: err.message
    }
  }
}
